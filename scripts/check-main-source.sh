#!/usr/bin/env bash
# Which branches may open a PR into main (main-via-staging.yml).
#
# main is promotion-only. The allowed heads are `staging` and a promote/<date>-<n>
# slice whose trusted replay holds (below). Hotfix/reverts land on staging first,
# then promote — a branch name alone never authorizes bypassing staging review.
#
#   HEAD_REF=<branch> HEAD_REPO=<owner/repo> REPO=<owner/repo> \
#     [HEAD_SHA=<event head sha> BASE_SHA=<event base sha> (a promote slice; gh authenticated)] \
#     bash scripts/check-main-source.sh
#
# Every allowed head must live in this repo: a fork's branch named 'staging'
# is not our staging. HEAD_REPO and REPO are required: an empty HEAD_REPO
# (e.g. a deleted fork) must fail, never skip the fork check.
#
# Bootstrap: this check runs for PRs targeting main. It does not move the
# GitHub default branch; activating it as a merge gate requires a ruleset /
# branch protection that requires the check named exactly
# "PRs into main must come from staging", which is the main-via-staging.yml
# job itself: this script's exit code fails that job. The check is
# commit-scoped: a PR from another branch at the very same SHA as staging
# delivers the identical commit.
# Forged same-name jobs are scripts/check-forged-gate-names.py's concern.
set -euo pipefail
: "${HEAD_REF:?HEAD_REF is required}"
: "${HEAD_REPO:?HEAD_REPO is required (empty means the head repo is gone; treat as a fork)}"
: "${REPO:?REPO is required}"

if [ "$HEAD_REPO" != "$REPO" ]; then
  echo "::error::PRs into main must come from a branch of $REPO, not a fork ('$HEAD_REPO')."
  exit 1
fi

case "$HEAD_REF" in
  staging)
    echo "::notice::'$HEAD_REF' is an allowed source for main."
    exit 0
    ;;
esac
# A merge-with-main promote slice (plan 2026-11-21-mvs-trusted-slice-replay) is admitted only when the trusted
# replay holds: provenance first, then git's own merge of the authorized parents, regenerated by the base's
# generator, equal to the head's tree. Every other outcome, and every error, rejects. HEAD_SHA and BASE_SHA are the
# event's immutable SHAs (main-via-staging.yml passes them); the replay checks them itself.
if [[ "$HEAD_REF" =~ ^promote/[0-9]{4}-[0-9]{2}-[0-9]{2}-[0-9]+$ ]]; then
  if ! python3 -I "$(dirname "${BASH_SOURCE[0]}")/replay-promote-slice.py"; then
    echo "::error::promote slice '$HEAD_REF' rejected: its trusted replay does not hold (reason above)."
    echo "Rebuild the slice from its staging cut merged with the current main, or promote 'staging' -> main."
    exit 1
  fi
  # The replay describes the merge against BASE_SHA; only the server can keep main from moving before the merge.
  # Without main's strict up-to-date policy a slice evaluated at one main could land on a newer one, so a slice is
  # never admitted until the rules GitHub applies to main carry it (a ruleset; classic protection is not read).
  # --slurp: one array per page, so a strict rule past the first page still counts. The reply stays in a file
  # (command substitution would strip NUL bytes and so alter it).
  rules=$(mktemp) || { echo "::error::promote slice '$HEAD_REF' rejected: no temp file for main's rules."; exit 1; }
  trap 'rm -f "$rules"' EXIT
  if ! gh api --paginate --slurp "repos/$REPO/rules/branches/main?per_page=100" >"$rules"; then
    echo "::error::promote slice '$HEAD_REF' rejected: could not read the rules for main, failing closed."
    exit 1
  fi
  # Strict decode (UTF-8, no NaN/Infinity, no duplicate keys), and every rule well formed, before any rule counts.
  if ! python3 -I -c 'import json, sys
def obj(kv):
    if len({k for k, _ in kv}) != len(kv): raise ValueError("duplicate key")
    return dict(kv)
def bad(c): raise ValueError(c)
pages = json.loads(open(sys.argv[1], "rb").read().decode("utf-8"), object_pairs_hook=obj, parse_constant=bad)
ok = isinstance(pages, list) and all(isinstance(p, list) and all(
    isinstance(r, dict) and isinstance(r.get("type"), str) and isinstance(r.get("parameters", {}), dict)
    for r in p) for p in pages)
sys.exit(0 if ok and any(r["type"] == "required_status_checks"
                         and r.get("parameters", {}).get("strict_required_status_checks_policy") is True
                         for p in pages for r in p) else 1)' "$rules"; then
    echo "::error::promote slice '$HEAD_REF' rejected: main's ruleset does not require branches to be up to date"
    echo "(strict required status checks), so the replayed merge may not be the one that lands. Enable it first."
    exit 1
  fi
  echo "::notice::promote slice '$HEAD_REF' is the trusted replay of its staging cut merged with main: allowed."
  exit 0
fi
echo "::error::PRs into main must come from 'staging' (got '$HEAD_REF')."
echo ""
echo "main is promotion-only. Merge this into staging first, verify there,"
echo "then promote staging -> main."
echo ""
echo "There is no hotfix/* or revert-* bypass. Land the fix on staging,"
echo "then open staging -> main."
exit 1
